def to_pytest(cases: list[TestCase]) -> str:
    body = [_PYTEST_HEADER]
    for i, c in enumerate(cases):
        exp_first = c.expected.split()[-3] if c.kind == "negative" and "7F" in c.expected else None
        assertion = (
            f"    resp = send(hx({c.request_hex!r}))\n"
            f"    assert resp, 'no response'\n"
        )
        if c.kind == "positive":
            first = c.request_hex  # positive SID known from expected
            pos = c.expected.replace("Positive response ", "").split()[0]
            assertion += f"    assert resp[0] == 0x{pos}, 'expected positive SID 0x{pos}'\n"
        else:
            parts = c.expected.split()
            # 7F <sid> <nrc>
            try:
                sid = parts[parts.index("7F") + 1]
                nrc = parts[parts.index("7F") + 2]
                assertion += (
                    f"    assert resp[0] == 0x7F and resp[2] == 0x{nrc}, "
                    f"'expected NRC 0x{nrc}'\n"
                )
            except (ValueError, IndexError):
                assertion += "    # review expected response manually\n"
        safe = "".join(ch if ch.isalnum() else "_" for ch in c.title.lower())[:50]
        body.append(f"def test_{i:02d}_{safe}():\n    # {c.precondition}\n{assertion}")
    return "\n".join(body)


def to_markdown(cases: list[TestCase]) -> str:
    rows = ["| # | Type | Title | Pre-condition | Request | Expected | Pass criteria |",
            "|---|------|-------|---------------|---------|----------|---------------|"]
    for i, c in enumerate(cases, 1):
        rows.append(f"| {i} | {c.kind} | {c.title} | {c.precondition} | `{c.request_hex}` | "
                    f"{c.expected} | {c.pass_criteria} |")
    return "\n".join(rows)
