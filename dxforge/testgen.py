"""Turn an engine result into a reviewable test case and runnable templates.

Exports are explicitly marked bench/HIL-only. DxForge never emits anything that
executes against a production vehicle, and never emits seed/key material.
"""
from __future__ import annotations

from dataclasses import dataclass

from .engine import DiagContext, EngineResult, Request, build_request_hex


@dataclass
class TestCase:
    title: str
    precondition: str
    request_hex: str
    expected: str
    pass_criteria: str
    kind: str  # "positive" | "negative"


def build_test_cases(req: Request, ctx: DiagContext, result: EngineResult) -> list[TestCase]:
    pre = f"Session = {ctx.session}; Security {'unlocked' if ctx.unlocked else 'locked'}"
    cases: list[TestCase] = []
    if result.outcome == "positive":
        cases.append(TestCase(
            title=f"{result.service_name}: positive response",
            precondition=pre, request_hex=result.request_hex,
            expected=f"Positive response {result.positive_response_hex}",
            pass_criteria=f"First response byte == {result.positive_response_hex.split()[0]}",
            kind="positive",
        ))
        # derive negative scenarios from candidate NRCs for coverage
        for nrc in result.candidate_nrcs[:4]:
            cases.append(TestCase(
                title=f"{result.service_name}: negative ({nrc:#04x})",
                precondition=pre + " (induce the error condition for this NRC)",
                request_hex=result.request_hex,
                expected=f"Negative response 7F {req.sid:02X} {nrc:02X}",
                pass_criteria=f"Response == 7F {req.sid:02X} {nrc:02X} when its condition holds",
                kind="negative",
            ))
    else:
        cases.append(TestCase(
            title=f"{result.service_name or 'Unknown'}: expected rejection",
            precondition=pre, request_hex=result.request_hex,
            expected=f"Negative response 7F {req.sid:02X} {result.nrc:02X} ({result.nrc_name})",
            pass_criteria=f"Response == 7F {req.sid:02X} {result.nrc:02X}",
            kind="negative",
        ))
    return cases


